#!/usr/bin/env node
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const taskDir = mkdtempSync(join(tmpdir(), 'review-cli-test-'));
const repo = join(taskDir, 'repo'), log = join(taskDir, 'harness.log');
const cli = new URL('./run-review.mjs', import.meta.url).pathname;
try {
  mkdirSync(repo);
  const git = (...args) => {
    const result = spawnSync('git', args, {cwd: repo, encoding: 'utf8'});
    assert.equal(result.status, 0, result.stderr);
  };
  git('init', '-q');
  writeFileSync(join(repo, '.gitignore'), '.agents/notes/\n');
  writeFileSync(join(repo, 'a.mjs'), 'export const a = 1;\n');
  git('add', '.');
  git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'fixture');
  git('update-ref', 'refs/remotes/origin/dev', 'HEAD');
  writeFileSync(join(repo, 'a.mjs'), 'export const a = 2;\n');
  git('add', 'a.mjs');
  const prompt = join(taskDir, 'context.md');
  writeFileSync(prompt, 'Synthetic review fixture.\n');
  const harness = join(taskDir, 'harness.mjs');
  writeFileSync(harness, `#!/usr/bin/env node
import {appendFileSync,writeFileSync,readFileSync} from 'node:fs';
const args=process.argv.slice(2), id=args.includes('exec')?'codex':'glm';
const input=readFileSync(0,'utf8');
appendFileSync(process.env.REVIEW_TEST_LOG,JSON.stringify({id,event:'start',time:Date.now(),input})+'\\n');
await new Promise(resolve=>setTimeout(resolve,500));
let verdict={verdict:'approve',summary:'Synthetic fixture',issues:[]};
if(process.env.REVIEW_TEST_CASE==='honesty') verdict.verify_honesty={verdict:'ok',reason:'Synthetic evidence checked'};
if((process.env.REVIEW_TEST_CASE==='negative'&&id==='glm')||(process.env.REVIEW_TEST_CASE==='final-negative'&&id==='codex')) verdict={verdict:'request_changes',summary:'Synthetic finding',issues:[{severity:'major',priority:2,file:'a.mjs',line:1,problem:'fixture defect',suggestion:'fixture fix'}]};
if(process.env.REVIEW_TEST_CASE==='drift'&&id==='glm') writeFileSync(process.env.REVIEW_TEST_SOURCE,'export const a = 3;\\n');
let text=process.env.REVIEW_TEST_CASE==='invalid'&&id==='glm'?'not json':JSON.stringify(verdict);
appendFileSync(process.env.REVIEW_TEST_LOG,JSON.stringify({id,event:'finish',time:Date.now()})+'\\n');
if(id==='codex') writeFileSync(args[args.indexOf('-o')+1],text);
else process.stdout.write(JSON.stringify({type:'text',part:{text}}));
`, {mode: 0o700});
  const env = {...process.env, CODEX_BIN: harness, OPENCODE_BIN: harness, REVIEW_TEST_LOG: log, REVIEW_TEST_SOURCE: join(repo, 'a.mjs')};
  delete env.AI_REVIEW_CONFIG;
  const run = (mode, extra = []) => {
    writeFileSync(log, '');
    const result = spawnSync(process.execPath, [cli, '--repo', repo, '--base', 'origin/dev', '--prompt', prompt, ...extra],
      {encoding: 'utf8', timeout: 30000, env: {...env, REVIEW_TEST_CASE: mode}});
    assert.ok(!result.error, result.error?.message);
    return {...result, summary: JSON.parse(result.stdout), events: readFileSync(log, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse)};
  };
  let result = run('approve');
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.summary.complete, true);
  assert.equal(result.summary.pass, true);
  assert.equal(new Set(result.summary.reviews.map(x => x._review.snapshot)).size, 1);
  assert.equal(new Set(result.summary.reviews.map(x => x._review.contextDigest)).size, 1);
  const starts = result.events.filter(x => x.event === 'start');
  const finishes = result.events.filter(x => x.event === 'finish');
  assert.equal(starts.length, 2);
  assert.deepEqual(starts.map(x => x.id).sort(), ['codex', 'glm']);
  assert.ok(Math.max(...starts.map(x=>x.time)) < Math.min(...finishes.map(x=>x.time)), 'Codex and GLM run in parallel');
  console.log('PASS parallel Codex/GLM dual lineage retains snapshot/context identity');
  const evidence = join(taskDir, 'evidence.json');
  const evidenceValue = {commands: [{command: 'fixture-check', exitCode: 0}], scope: 'synthetic evidence'};
  writeFileSync(evidence, JSON.stringify(evidenceValue));
  result = run('honesty', ['--verify-evidence', evidence]);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.summary.pass, true);
  assert.equal(new Set(result.summary.reviews.map(x => x._review.contextDigest)).size, 1);
  assert.ok(result.summary.reviews.every(x => x.verify_honesty?.verdict === 'ok'));
  assert.ok(result.events.filter(x => x.event === 'start').every(x => x.input.includes(JSON.stringify(evidenceValue)) && x.input.includes('verify_honesty')));
  console.log('PASS structured evidence reaches every lineage and requires honesty');
  result = run('approve', ['--verify-evidence', evidence]);
  assert.equal(result.status, 1);
  assert.equal(result.summary.complete, false);
  assert.equal(result.summary.pass, false);
  assert.ok(['codex', 'glm'].every(id => result.events.filter(x => x.id === id && x.event === 'start').length === 2));
  console.log('PASS omitted honesty cannot release after bounded retries');
  result = run('negative');
  assert.equal(result.status, 1);
  assert.equal(result.summary.complete, true);
  assert.equal(result.summary.pass, false);
  console.log('PASS valid GLM P2 blocks aggregate release');
  result = run('invalid');
  assert.equal(result.status, 1);
  assert.equal(result.summary.complete, false);
  assert.equal(result.summary.pass, false);
  assert.equal(result.events.filter(x => x.id === 'glm' && x.event === 'start').length, 2);
  assert.equal(result.events.filter(x => x.id === 'codex' && x.event === 'start').length, 1);
  console.log('PASS invalid output bounded retries cannot replace missing lineage');
  result = run('final-negative');
  assert.equal(result.summary.complete, true);
  assert.equal(result.summary.pass, false);
  assert.equal(result.events.filter(x=>x.id==='codex'&&x.event==='start').length, 1);
  console.log('PASS Codex finding blocks release');
  result = run('drift');
  assert.equal(result.summary.complete, false);
  assert.equal(result.summary.pass, false);
  writeFileSync(join(repo, 'a.mjs'), 'export const a = 2;\n');
  console.log('PASS snapshot drift during review invalidates both lineages');
  result = run('approve', ['--reviewer', 'codex']);
  assert.equal(result.status, 1);
  assert.equal(result.summary.complete, false);
  assert.equal(result.summary.pass, false);
  assert.equal(result.events.filter(x => x.event === 'start').length, 1);
  console.log('PASS single-reviewer diagnostic cannot release');
} finally { rmSync(taskDir, {recursive: true, force: true}); }
